	public static String of(Module m) {
		String icon = MODULES.get(m.id());
		return icon != null ? icon : Icon.MODS;
	}

	public static String of(Setting<?> s) {
		String icon = SETTINGS.get(s.id());
		if (icon != null) return icon;
		if (s.id().contains("color")) return Icon.PALETTE;
		if (s instanceof ModeSetting) return Icon.DASHBOARD;
		if (s instanceof ColorSetting) return Icon.PALETTE;
		if (s instanceof TextSetting) return Icon.EDIT;
		if (s instanceof BooleanSetting || s instanceof NumberSetting) return Icon.TUNE;
		return Icon.TUNE;
	}
