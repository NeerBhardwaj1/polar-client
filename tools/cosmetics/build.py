"""Builds every Polar cosmetic into server/public/cosmetics (textures, models, catalog.json) and the catalogue the
server checks against (server/src/catalog.js).

    python tools/cosmetics/build.py            # everything
    python tools/cosmetics/build.py wings_frost cape_aurora   # just these (the catalogue still lists all)
"""
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, 'server', 'public', 'cosmetics')

import auras  # noqa: E402
import backs  # noqa: E402
import capes  # noqa: E402
import heads  # noqa: E402
import wings  # noqa: E402

KINDS = [('cape', capes), ('wings', wings), ('head', heads), ('back', backs), ('aura', auras)]
COLLECTIONS = [
    {'id': 'polar', 'name': 'Polar Collection'},
    {'id': 'celestial', 'name': 'Celestial'},
    {'id': 'inferno', 'name': 'Inferno'},
    {'id': 'cosmic', 'name': 'Cosmic'},
    {'id': 'nature', 'name': 'Nature'},
    {'id': 'neon', 'name': 'Neon'},
    {'id': 'royal', 'name': 'Royal'},
    {'id': 'cute', 'name': 'Cute'},
    {'id': 'classic', 'name': 'Classic'},
    {'id': 'special', 'name': 'Special'},
]
RARITY = ['common', 'rare', 'epic', 'legendary']
FIELDS = ('id', 'name', 'description', 'collection', 'rarity')


def main(only):
    os.makedirs(OUT, exist_ok=True)
    catalog = {'format': 1, 'collections': COLLECTIONS, 'items': []}
    previous = {}
    path = os.path.join(OUT, 'catalog.json')
    if os.path.exists(path):
        previous = {i['id']: i for i in json.load(open(path)).get('items', [])}
    ids = set()
    for kind, module in KINDS:
        for item in module.ITEMS:
            assert item['id'] not in ids, f"duplicate id {item['id']}"
            ids.add(item['id'])
            assert item.get('rarity', 'common') in RARITY, item['id']
            entry = {k: item[k] for k in FIELDS if k in item}
            entry['type'] = kind
            if item.get('special'):
                entry['special'] = True
            if item.get('tint'):
                entry['tint'] = True
                entry['defaultColor'] = item.get('defaultColor', '#ffffff')
            if only and item['id'] not in only and item['id'] in previous:
                built = {k: v for k, v in previous[item['id']].items() if k not in entry and k not in ('type', 'special', 'tint', 'defaultColor')}
            else:
                print(f"  {kind:5} {item['id']}")
                built = module.build(OUT, item)
            entry.update(built)
            catalog['items'].append(entry)
    # the Polar badge shown next to names
    shutil.copyfile(os.path.join(ROOT, 'branding', 'png', 'polar-icon-32.png'), os.path.join(OUT, 'badge.png'))
    catalog['badge'] = 'badge.png'
    with open(path, 'w') as fh:
        json.dump(catalog, fh, indent=1)
    # the server only needs to know what exists, what kind it is, and whether it's special
    slim = {'format': 1, 'items': [{k: i[k] for k in ('id', 'name', 'type', 'special', 'tint') if k in i} for i in catalog['items']]}
    with open(os.path.join(ROOT, 'server', 'src', 'catalog.js'), 'w') as fh:
        fh.write('// Generated by tools/cosmetics/build.py from the cosmetics in tools/cosmetics/: do not edit by hand.\n')
        fh.write(f'export default {json.dumps(slim, indent=1)};\n')
    print(f"{len(catalog['items'])} cosmetics -> {os.path.relpath(OUT, ROOT)}")


if __name__ == '__main__':
    main(set(sys.argv[1:]))
